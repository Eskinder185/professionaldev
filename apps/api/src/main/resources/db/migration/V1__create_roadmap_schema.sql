CREATE TABLE roadmaps (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR(100) NOT NULL,
    title VARCHAR(200) NOT NULL,
    description TEXT NOT NULL,
    target_role VARCHAR(160) NOT NULL,
    estimated_weeks SMALLINT NOT NULL,
    CONSTRAINT uk_roadmaps_slug UNIQUE (slug),
    CONSTRAINT ck_roadmaps_slug_format CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    CONSTRAINT ck_roadmaps_title_not_blank CHECK (btrim(title) <> ''),
    CONSTRAINT ck_roadmaps_description_not_blank CHECK (btrim(description) <> ''),
    CONSTRAINT ck_roadmaps_target_role_not_blank CHECK (btrim(target_role) <> ''),
    CONSTRAINT ck_roadmaps_estimated_weeks CHECK (estimated_weeks BETWEEN 1 AND 520)
);

CREATE TABLE roadmap_stages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    roadmap_id BIGINT NOT NULL,
    stage_order SMALLINT NOT NULL,
    title VARCHAR(200) NOT NULL,
    CONSTRAINT fk_roadmap_stages_roadmap
        FOREIGN KEY (roadmap_id) REFERENCES roadmaps (id) ON DELETE CASCADE,
    CONSTRAINT uk_roadmap_stages_order UNIQUE (roadmap_id, stage_order),
    CONSTRAINT ck_roadmap_stages_order CHECK (stage_order > 0),
    CONSTRAINT ck_roadmap_stages_title_not_blank CHECK (btrim(title) <> '')
);

CREATE TABLE stage_outcomes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stage_id BIGINT NOT NULL,
    outcome_order SMALLINT NOT NULL,
    outcome_text TEXT NOT NULL,
    CONSTRAINT fk_stage_outcomes_stage
        FOREIGN KEY (stage_id) REFERENCES roadmap_stages (id) ON DELETE CASCADE,
    CONSTRAINT uk_stage_outcomes_order UNIQUE (stage_id, outcome_order),
    CONSTRAINT ck_stage_outcomes_order CHECK (outcome_order > 0),
    CONSTRAINT ck_stage_outcomes_text_not_blank CHECK (btrim(outcome_text) <> '')
);
