CREATE TABLE application_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject VARCHAR(200) NOT NULL,
    display_name VARCHAR(200) NOT NULL,
    CONSTRAINT uk_application_users_subject UNIQUE (subject),
    CONSTRAINT ck_application_users_subject_not_blank CHECK (btrim(subject) <> ''),
    CONSTRAINT ck_application_users_display_name_not_blank CHECK (btrim(display_name) <> '')
);

CREATE TABLE user_stage_progress (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    stage_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL,
    completed_at TIMESTAMP WITH TIME ZONE,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_user_stage_progress_user
        FOREIGN KEY (user_id) REFERENCES application_users (id) ON DELETE CASCADE,
    CONSTRAINT fk_user_stage_progress_stage
        FOREIGN KEY (stage_id) REFERENCES roadmap_stages (id) ON DELETE CASCADE,
    CONSTRAINT uk_user_stage_progress_user_stage UNIQUE (user_id, stage_id),
    CONSTRAINT ck_user_stage_progress_status
        CHECK (status IN ('NOT_STARTED', 'IN_PROGRESS', 'COMPLETED')),
    CONSTRAINT ck_user_stage_progress_completion
        CHECK ((status = 'COMPLETED' AND completed_at IS NOT NULL)
            OR (status <> 'COMPLETED' AND completed_at IS NULL)),
    CONSTRAINT ck_user_stage_progress_version CHECK (version >= 0)
);

CREATE INDEX ix_user_stage_progress_stage_id ON user_stage_progress (stage_id);

